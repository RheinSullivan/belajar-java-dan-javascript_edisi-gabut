package com.priasolo.javapemula; // "Package" ini adalah tempat resmi buat "Class JavaPemula", jadi Project punya susunan Folder yg rapi.

/**
 *
 * @author rheinsullivan
 */
public class JavaPemula { // "JavaPemula" adalah nama "Class", ini seperti judul besar dari program kecil yg isinya latihan pertama belajar Java.

    public static void main(String[] args) { // "main" adalah "Method" utama, Java mulai membaca program dari sini, seperti orang mulai membaca surat dari bagian pembuka.
        System.out.println("Hello World!"); // "System.out.println" menampilkan tulisan ke "Terminal", "Hello World" biasanya dipakai buat ngetes apakah Java sudah jalan dengan benar.
    } // Kurung kurawal ini nutup "Method Main", jadi perintah utama selesai di sini.
} // Kurung kurawal ini nutup "Class JavaPemula", jadi File latihan dasar ini selesai di sini.

/*
 * Kesimpulan:
 * - File ini adalah latihan paling dasar buat memastikan Java bisa jalan di laptop.
 * - "Hello World" itu seperti salam pertama dari program ke manusia.
 * - "Class JavaPemula" adalah wadah utama dari Code ini.
 * - "main" adalah pintu masuk program Java.
 * - "String[] args" adalah tempat data tambahan dari luar program bisa masuk, tapi di latihan ini belum dipakai.
 * - "System.out.println" adalah alat buat menampilkan teks ke "Terminal".
 * - Contoh sehari hari adalah mesin kasir yg setelah dinyalakan menampilkan tulisan siap dipakai di layar kecilnya.
 * - Kalau tulisan "Hello World" muncul, berarti Java, JDK, dan cara menjalankan program sudah bekerja.
 */